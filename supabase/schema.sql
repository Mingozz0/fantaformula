-- GRIDF1 initial schema for Supabase PostgreSQL.
-- This file mirrors migration gridf1_initial_schema applied to the Mingo project.
-- Historical MySQL users/passwords are deliberately excluded.

create schema if not exists private;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (length(btrim(display_name)) between 2 and 80),
  created_at timestamptz not null default now()
);

create table public.seasons (
  id integer generated by default as identity primary key,
  year integer not null unique check (year between 1950 and 2100)
);

create table public.drivers (
  id bigint generated by default as identity primary key,
  legacy_key text unique,
  first_name text not null,
  last_name text not null,
  nationality text,
  birth_date date
);

create table public.constructors (
  id bigint generated by default as identity primary key,
  legacy_key text unique,
  canonical_name text not null unique
);

create table public.season_constructors (
  season_id integer not null references public.seasons(id),
  constructor_id bigint not null references public.constructors(id),
  display_name text not null,
  primary key (season_id, constructor_id),
  unique (season_id, display_name)
);

create table public.season_drivers (
  season_id integer not null,
  driver_id bigint not null references public.drivers(id),
  constructor_id bigint not null,
  car_number smallint check (car_number between 0 and 99),
  short_name text,
  primary key (season_id, driver_id),
  foreign key (season_id, constructor_id)
    references public.season_constructors(season_id, constructor_id)
);

create index season_drivers_constructor_idx
  on public.season_drivers(season_id, constructor_id);

create table public.races (
  id bigint generated by default as identity primary key,
  season_id integer not null references public.seasons(id),
  round smallint not null check (round > 0),
  name text not null,
  circuit text not null,
  city text,
  country text,
  race_starts_at timestamptz,
  sprint_starts_at timestamptz,
  lineup_deadline_at timestamptz,
  unique (season_id, round),
  unique (id, season_id)
);

create index races_season_start_idx on public.races(season_id, race_starts_at);

create table public.race_driver_results (
  race_id bigint not null,
  season_id integer not null,
  driver_id bigint not null,
  grid_position smallint check (grid_position > 0),
  finish_position smallint check (finish_position > 0),
  result_status text not null default 'finished'
    check (result_status in ('finished', 'dnf', 'dns', 'dsq', 'other')),
  fastest_lap boolean not null default false,
  driver_of_the_day boolean not null default false,
  primary key (race_id, driver_id),
  foreign key (race_id, season_id) references public.races(id, season_id),
  foreign key (season_id, driver_id)
    references public.season_drivers(season_id, driver_id),
  check (result_status <> 'finished' or finish_position is not null)
);

create index race_driver_results_driver_idx
  on public.race_driver_results(driver_id, race_id);

create table public.sprint_driver_results (
  race_id bigint not null,
  season_id integer not null,
  driver_id bigint not null,
  grid_position smallint check (grid_position > 0),
  finish_position smallint check (finish_position > 0),
  result_status text not null default 'finished'
    check (result_status in ('finished', 'dnf', 'dns', 'dsq', 'other')),
  primary key (race_id, driver_id),
  foreign key (race_id, season_id) references public.races(id, season_id),
  foreign key (season_id, driver_id)
    references public.season_drivers(season_id, driver_id),
  check (result_status <> 'finished' or finish_position is not null)
);

create index sprint_driver_results_driver_idx
  on public.sprint_driver_results(driver_id, race_id);

create table public.race_constructor_results (
  race_id bigint not null,
  season_id integer not null,
  constructor_id bigint not null,
  fastest_pit_stop boolean not null default false,
  primary key (race_id, constructor_id),
  foreign key (race_id, season_id) references public.races(id, season_id),
  foreign key (season_id, constructor_id)
    references public.season_constructors(season_id, constructor_id)
);

create table public.leagues (
  id uuid primary key default gen_random_uuid(),
  season_id integer not null references public.seasons(id),
  name text not null check (length(btrim(name)) between 3 and 100),
  invite_code text not null unique
    default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)),
  created_by uuid not null references auth.users(id),
  status text not null default 'recruiting'
    check (status in ('recruiting', 'active', 'completed')),
  created_at timestamptz not null default now(),
  unique (id, season_id)
);

create index leagues_created_by_idx on public.leagues(created_by);
create index leagues_season_idx on public.leagues(season_id);

create table public.league_members (
  league_id uuid not null references public.leagues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('admin', 'member')),
  joined_at timestamptz not null default now(),
  primary key (league_id, user_id)
);

create unique index league_one_admin_idx on public.league_members(league_id)
  where role = 'admin';
create index league_members_user_idx on public.league_members(user_id, league_id);

create table public.fantasy_teams (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null,
  season_id integer not null,
  user_id uuid not null,
  name text not null check (length(btrim(name)) between 2 and 80),
  constructor_id bigint not null,
  driver_one_id bigint not null,
  driver_two_id bigint not null,
  driver_three_id bigint not null,
  created_at timestamptz not null default now(),
  unique (league_id, user_id),
  unique (id, league_id, season_id),
  foreign key (league_id, season_id) references public.leagues(id, season_id),
  foreign key (league_id, user_id)
    references public.league_members(league_id, user_id) on delete cascade,
  foreign key (season_id, constructor_id)
    references public.season_constructors(season_id, constructor_id),
  foreign key (season_id, driver_one_id)
    references public.season_drivers(season_id, driver_id),
  foreign key (season_id, driver_two_id)
    references public.season_drivers(season_id, driver_id),
  foreign key (season_id, driver_three_id)
    references public.season_drivers(season_id, driver_id),
  check (driver_one_id <> driver_two_id
    and driver_one_id <> driver_three_id
    and driver_two_id <> driver_three_id)
);

create index fantasy_teams_user_idx on public.fantasy_teams(user_id);

create table public.lineups (
  id uuid primary key default gen_random_uuid(),
  fantasy_team_id uuid not null,
  league_id uuid not null,
  season_id integer not null,
  race_id bigint not null,
  driver_one_id bigint not null,
  driver_two_id bigint not null,
  captain_driver_id bigint,
  submitted_at timestamptz not null default now(),
  unique (fantasy_team_id, race_id),
  foreign key (fantasy_team_id, league_id, season_id)
    references public.fantasy_teams(id, league_id, season_id),
  foreign key (race_id, season_id) references public.races(id, season_id),
  foreign key (season_id, driver_one_id)
    references public.season_drivers(season_id, driver_id),
  foreign key (season_id, driver_two_id)
    references public.season_drivers(season_id, driver_id),
  check (driver_one_id <> driver_two_id),
  check (captain_driver_id is null
    or captain_driver_id in (driver_one_id, driver_two_id))
);

create index lineups_race_idx on public.lineups(race_id, league_id);

create function private.check_league_member_limit()
returns trigger language plpgsql set search_path = '' as $$
begin
  perform 1 from public.leagues where id = new.league_id for update;
  if (select count(*) from public.league_members where league_id = new.league_id) >= 7 then
    raise exception 'A league may have at most seven members';
  end if;
  return new;
end;
$$;

create trigger league_member_limit before insert on public.league_members
for each row execute function private.check_league_member_limit();

create function private.add_league_creator()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.league_members(league_id, user_id, role)
  values (new.id, new.created_by, 'admin');
  return new;
end;
$$;

create trigger league_creator after insert on public.leagues
for each row execute function private.add_league_creator();

-- Joining requires the invite code. Direct writes to league_members remain closed.
create function public.join_league(code text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare target public.leagues%rowtype;
declare caller uuid := (select auth.uid());
begin
  if caller is null then
    raise exception 'Authentication required';
  end if;
  select * into target from public.leagues
  where invite_code = upper(btrim(code)) and status = 'recruiting'
  for update;
  if not found then
    raise exception 'Invite code not found or league closed';
  end if;
  insert into public.league_members(league_id, user_id, role)
  values (target.id, caller, 'member')
  on conflict (league_id, user_id) do nothing;
  return target.id;
end;
$$;

revoke all on function public.join_league(text) from public, anon;
grant execute on function public.join_league(text) to authenticated;

create function private.check_league_activation()
returns trigger language plpgsql set search_path = '' as $$
declare member_count integer;
declare team_count integer;
begin
  if new.status = 'active' and old.status <> 'active' then
    select count(*) into member_count from public.league_members where league_id = new.id;
    select count(*) into team_count from public.fantasy_teams where league_id = new.id;
    if member_count not between 4 and 7 or team_count <> member_count then
      raise exception 'A league requires 4-7 members, each with a complete team';
    end if;
  end if;
  return new;
end;
$$;

create trigger league_activation before update of status on public.leagues
for each row execute function private.check_league_activation();

create function private.check_lineup()
returns trigger language plpgsql set search_path = '' as $$
declare roster public.fantasy_teams%rowtype;
declare deadline timestamptz;
begin
  select * into roster from public.fantasy_teams where id = new.fantasy_team_id;
  if not found or new.driver_one_id not in
      (roster.driver_one_id, roster.driver_two_id, roster.driver_three_id)
    or new.driver_two_id not in
      (roster.driver_one_id, roster.driver_two_id, roster.driver_three_id) then
    raise exception 'The lineup must contain two drivers from the fantasy team';
  end if;
  select lineup_deadline_at into deadline from public.races where id = new.race_id;
  if deadline is null then
    raise exception 'The lineup deadline has not been set for this race';
  end if;
  if now() >= deadline then
    raise exception 'The lineup deadline has passed';
  end if;
  new.submitted_at := now();
  return new;
end;
$$;

create trigger lineup_rules before insert or update on public.lineups
for each row execute function private.check_lineup();

create function private.prevent_roster_change_after_lineup()
returns trigger language plpgsql set search_path = '' as $$
begin
  if exists (select 1 from public.lineups where fantasy_team_id = old.id) then
    raise exception 'A team with submitted lineups cannot change its roster';
  end if;
  return new;
end;
$$;

create trigger roster_lock before update of
  constructor_id, driver_one_id, driver_two_id, driver_three_id
on public.fantasy_teams for each row
when (old.constructor_id is distinct from new.constructor_id
  or old.driver_one_id is distinct from new.driver_one_id
  or old.driver_two_id is distinct from new.driver_two_id
  or old.driver_three_id is distinct from new.driver_three_id)
execute function private.prevent_roster_change_after_lineup();

-- Boolean helpers live outside the Data API schema to avoid policy recursion.
create function private.is_league_member(target_league uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.league_members
    where league_id = target_league and user_id = (select auth.uid())
  );
$$;

create function private.is_league_admin(target_league uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.league_members
    where league_id = target_league
      and user_id = (select auth.uid()) and role = 'admin'
  );
$$;

